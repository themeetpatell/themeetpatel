#!/usr/bin/env node
/**
 * Appends the essay corpus to public/llms-full.txt at build time.
 *
 * Why: llms-full.txt is the one file an answer engine can read once and answer
 * from for months. Until now it carried the entity, the thesis, the vocabulary
 * and an FAQ — but only a LINK to the writing. A model that reads it therefore
 * knows what Meet Patel claims and nothing about how he argues, which is the
 * half that gets cited.
 *
 * SHAPE, and it is a deliberate compromise:
 *   · Thesis-aligned essays (the pillar categories) go in as full text, newest
 *     first, capped at FULL_TEXT_LIMIT so the file stays a document rather than
 *     a database dump. Consumers do truncate.
 *   · Every other published essay gets title + date + excerpt + URL, so the
 *     corpus is complete and nothing is hidden — it just is not inlined.
 *
 * FAIL-SAFE, non-negotiable. This runs inside `prebuild` on Vercel. A missing
 * env var or a slow database must never fail a deploy over a nice-to-have file,
 * so every failure path warns and exits 0, leaving the committed file exactly
 * as it is. The site is correct without this script; it is only richer with it.
 *
 * Idempotent: the generated section lives between two markers and is replaced
 * wholesale on every run, so running it twice produces the same file.
 *
 * Usage:
 *   node scripts/build-llms-full.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const FILE = 'public/llms-full.txt';
const BEGIN = '<!-- BEGIN:ESSAY-CORPUS — generated by scripts/build-llms-full.mjs, do not edit by hand -->';
const END = '<!-- END:ESSAY-CORPUS -->';

/** Categories that belong to the three thesis pillars. Full text for these. */
const PILLAR_CATEGORIES = new Set([
  'Data & Analytics',
  'Strategy',
  'Business Strategy',
  'Product-Led Management',
  'User-led Growth',
  'Entrepreneurship',
]);

/** How many essays are inlined in full. The rest are listed with excerpts. */
const FULL_TEXT_LIMIT = 15;

const SITE = 'https://www.themeetpatel.com';

/** Give up rather than hold a deploy hostage to a slow read. */
const FETCH_TIMEOUT_MS = 20_000;

const warn = (message) => console.warn(`  ! build-llms-full: ${message}`);

/**
 * HTML to readable plain text. Not a sanitiser — the input is our own
 * admin-authored rich text, and the output is a text file, so the only job is
 * to keep the prose and the structure while dropping the markup.
 * @param {string} html
 * @returns {string}
 */
export const htmlToText = (html) =>
  String(html)
    .replace(/<(script|style)[\s\S]*?<\/\1>/gi, '')
    .replace(/<h([1-6])[^>]*>/gi, (_, level) => `\n\n${'#'.repeat(Math.min(Number(level) + 2, 6))} `)
    .replace(/<\/h[1-6]>/gi, '\n')
    .replace(/<li[^>]*>/gi, '\n- ')
    .replace(/<\/(p|div|section|ul|ol|blockquote|pre|table|tr)>/gi, '\n\n')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#(\d+);/g, (_, code) => String.fromCharCode(Number(code)))
    .replace(/&#x([0-9a-f]+);/gi, (_, code) => String.fromCharCode(parseInt(code, 16)))
    .replace(/[ \t]+/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

const toDay = (value) => (value ? String(value).slice(0, 10) : 'undated');

async function fetchArticles() {
  const url = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
  const key =
    process.env.SUPABASE_ANON_KEY ||
    process.env.VITE_SUPABASE_ANON_KEY ||
    process.env.VITE_SUPABASE_PUBLISHABLE_KEY;

  // Guarded here rather than by importing api/_supabase.js: createClient throws
  // on undefined credentials, and a throw at import time cannot be caught into
  // a warning.
  if (!url || !key) {
    warn('SUPABASE_URL / SUPABASE_ANON_KEY not set — leaving the committed file unchanged.');
    return null;
  }

  const { createClient } = await import('@supabase/supabase-js');
  const supabase = createClient(url, key);

  const query = supabase
    .from('articles')
    .select('slug, title, excerpt, category, published_at, date, content_html, ai_summary, canonical_url')
    .eq('status', 'published')
    .order('published_at', { ascending: false, nullsFirst: false });

  const timeout = new Promise((_, reject) =>
    setTimeout(() => reject(new Error(`timed out after ${FETCH_TIMEOUT_MS}ms`)), FETCH_TIMEOUT_MS)
  );

  const { data, error } = await Promise.race([query, timeout]);
  if (error) throw error;
  return (data || []).filter((a) => a.slug && a.title);
}

/**
 * Render the corpus section.
 * @param {Array<object>} articles
 */
export function renderCorpus(articles) {
  const isPillar = (a) => PILLAR_CATEGORIES.has(a.category);
  const full = articles.filter(isPillar).slice(0, FULL_TEXT_LIMIT);
  const inlined = new Set(full.map((a) => a.slug));
  const listed = articles.filter((a) => !inlined.has(a.slug));

  const lines = [
    BEGIN,
    '',
    '---',
    '',
    '## 6. The essays',
    '',
    `${articles.length} published essays. The ${full.length} below are reproduced in full; ` +
      `the remaining ${listed.length} are listed after them with their summaries and URLs. ` +
      `Generated from the live CMS on ${new Date().toISOString().slice(0, 10)} — ` +
      `the canonical version of any essay is always the URL given with it.`,
    '',
  ];

  for (const a of full) {
    const body = htmlToText(a.content_html || '');
    lines.push(
      `### ${a.title}`,
      '',
      `- URL: ${SITE}/blogs/${a.slug}`,
      `- Published: ${toDay(a.published_at || a.date)}`,
      `- Category: ${a.category || 'Uncategorised'}`,
      `- Author: Meet Patel`,
      ''
    );
    if (a.ai_summary) lines.push(`**Summary.** ${a.ai_summary}`, '');
    lines.push(body || a.excerpt || '(No body text available — read the canonical URL above.)', '', '---', '');
  }

  if (listed.length) {
    lines.push('### Every other published essay', '');
    for (const a of listed) {
      const summary = a.ai_summary || a.excerpt || '';
      lines.push(
        `- **${a.title}** (${toDay(a.published_at || a.date)}, ${a.category || 'Uncategorised'}) — ` +
          `${SITE}/blogs/${a.slug}${summary ? ` — ${summary}` : ''}`
      );
    }
    lines.push('');
  }

  lines.push(END, '');
  return lines.join('\n');
}

export async function main() {
  let original;
  try {
    original = readFileSync(FILE, 'utf8');
  } catch (err) {
    warn(`could not read ${FILE} (${err.message}) — nothing written.`);
    return;
  }

  let articles;
  try {
    articles = await fetchArticles();
  } catch (err) {
    warn(`article fetch failed (${err.message}) — leaving the committed file unchanged.`);
    return;
  }
  if (!articles) return;
  if (articles.length === 0) {
    warn('zero published articles returned — refusing to write an empty corpus.');
    return;
  }

  // Strip any previous generated block, then append the new one. Never mutates
  // the hand-written canon above it.
  const beginAt = original.indexOf(BEGIN);
  const endAt = original.indexOf(END);
  const canon =
    beginAt !== -1 && endAt > beginAt
      ? `${original.slice(0, beginAt)}${original.slice(endAt + END.length)}`
      : original;

  const next = `${canon.trimEnd()}\n\n${renderCorpus(articles)}`;

  if (next === original) {
    console.log('llms-full.txt: essay corpus already current.');
    return;
  }

  writeFileSync(FILE, next, 'utf8');
  const kb = (Buffer.byteLength(next, 'utf8') / 1024).toFixed(1);
  const fullCount = articles.filter((a) => PILLAR_CATEGORIES.has(a.category)).slice(0, FULL_TEXT_LIMIT).length;
  console.log(
    `llms-full.txt: ${articles.length} essays (${fullCount} in full, ${articles.length - fullCount} listed) — ${kb} KB.`
  );
}

// Run only when invoked directly, so htmlToText and renderCorpus stay testable
// without the script writing a file as a side effect of being imported.
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  main().catch((err) => {
    // Last resort. This file is an enhancement; a deploy must never die for it.
    warn(`unexpected failure (${err.message}) — leaving the committed file unchanged.`);
  });
}
